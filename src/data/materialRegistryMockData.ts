const DEMO_ARTISAN_ID = 'demo-artisan';

const withComputed = (
  batch: Omit<MaterialBatchWithAllocations, 'allocations' | 'allocatedQty' | 'remainingQty'> & {
    allocations?: MaterialBatchWithAllocations['allocations'];
  }
): MaterialBatchWithAllocations => {
  const allocations = batch.allocations || [];
  const allocatedQty = allocations.reduce((sum, a) => sum + a.allocated_qty, 0);
  return {
    ...batch,
    allocations,
    allocatedQty,
    remainingQty: batch.purchased_qty - allocatedQty,
  };
};

